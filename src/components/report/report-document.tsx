import { Document, Page, View, Text, StyleSheet } from "@react-pdf/renderer";
import { PurLinLineState } from "../hooks/use-purlin-line";
import { AnalaysisData } from "../results/results-display";

const styles = StyleSheet.create({
  page: { padding: 40, fontSize: 11, color: "#1f2937", fontFamily: "Helvetica" },
  header: {
    fontSize: 18,
    fontWeight: 700,
    color: "#1F365C",
    marginBottom: 4,
    fontFamily: "Helvetica-Bold",
  },
  subtitle: { fontSize: 10, color: "#6b7280", marginBottom: 20 },
  sectionTitle: {
    fontSize: 12,
    fontFamily: "Helvetica-Bold",
    color: "#1F365C",
    backgroundColor: "#e8eef6",
    padding: 6,
    marginTop: 16,
    marginBottom: 8,
  },
  row: {
    flexDirection: "row",
    borderBottom: "1px solid #eee",
    paddingVertical: 4,
  },
  label: { width: "55%", color: "#555" },
  value: { width: "45%", fontFamily: "Helvetica-Bold" },
  bigValue: { fontSize: 16, fontFamily: "Helvetica-Bold", color: "#007599" },
  footer: {
    position: "absolute",
    bottom: 24,
    left: 40,
    right: 40,
    fontSize: 8,
    color: "#9ca3af",
    textAlign: "center",
  },
});

function Row({ label, value }: { label: string; value: string }) {
  return (
    <View style={styles.row}>
      <Text style={styles.label}>{label}</Text>
      <Text style={styles.value}>{value}</Text>
    </View>
  );
}

export default function ReportDocument({
  input,
  output,
}: {
  input: PurLinLineState;
  output: AnalaysisData;
}) {
  const spans = input.spans.map((s) => s.value).join(", ");

  return (
    <Document title="PurlinLine Analysis Report">
      <Page size="A4" style={styles.page}>
        <Text style={styles.header}>PurlinLine Analysis Report</Text>
        <Text style={styles.subtitle}>Generated by RunToSolve</Text>

        <Text style={styles.sectionTitle}>Results</Text>
        <View style={{ marginBottom: 8 }}>
          <Text style={{ color: "#555", marginBottom: 2 }}>
            Allowable roof pressure
          </Text>
          <Text style={styles.bigValue}>
            {output.capacity.value} {output.capacity.unit}
          </Text>
        </View>
        <Row label="Predicted failure limit state" value={output.failureLimitState} />
        <Row label="Failure location (in.)" value={String(output.failureLocation)} />

        <Text style={styles.sectionTitle}>Section</Text>
        <Row label="Load direction" value={input.loadDirection} />
        <Row label="Roof slope (deg.)" value={String(input.roofSlope)} />
        <Row label="Cross section" value={input.crossSection} />
        <Row label="Deck type" value={input.deckType} />

        <Text style={styles.sectionTitle}>Geometry</Text>
        <Row label="Spans (ft.)" value={spans} />
        <Row label="Lap length (ft.)" value={String(input.lapLength)} />
        <Row label="Spacing (ft.)" value={String(input.spacing)} />
        <Row label="Frame flange width (in.)" value={String(input.frameFlangeWidth)} />

        <Text style={styles.footer}>
          © {new Date().getFullYear()} RunToSolve, LLC — This report is generated
          from user-provided inputs.
        </Text>
      </Page>
    </Document>
  );
}
